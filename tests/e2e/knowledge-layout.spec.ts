  await sheet.getByLabel("知识标题", { exact: true }).fill("保留草稿");
  await page.screenshot({ path: join(shots, "mobile-create-light.png"), animations: "disabled" });
  await page.keyboard.press("Escape"); await expect(sheet).toBeHidden();
