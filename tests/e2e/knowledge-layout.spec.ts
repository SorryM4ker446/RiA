test("tool knowledge entries show readable summaries, preserve raw editing and keep technical records folded", { tag: "@integration" }, async ({ page, app }) => {
  const errors: string[] = [], trackedImages: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  page.on("request", request => { if (request.url().includes("tracker.invalid")) trackedImages.push(request.url()); });
  await page.goto(`${app.origin}/knowledge`);
  const recordKey = "tool:webSearch:原神-genshin-impact-游戏评价-2025";
  const original = ["version=tool-memory-v1", "tool=webSearch", "trigger=auto", "time=2026-09-17T02:57:00.393Z", "fingerprint=ce9cf191", "quality=0.650", "summary=Web 搜索「原神 Genshin Impact 游戏评价 2025」返回 4 条结果。", "tags=web-search", 'assistant=## 评价要点\n\n**探索体验**：开放世界内容丰富。\n\n[查看来源](https://example.com/review)\n\n![tracker](https://tracker.invalid/pixel.png)'].join("\n");
  const added = await browserApi(page, "/api/knowledge", "POST", { key: recordKey, value: original }); expect(added.status).toBe(201);
  await browserApi(page, "/api/knowledge", "POST", { key: "tool:webSearch:原神-2025-最新评价", value: original.replace("原神 Genshin Impact 游戏评价 2025", "原神 2025 最新评价").replace("ce9cf191", "aabbcc") });
  const note = "资料范围\n游戏资讯\n社区评价\n发布日期\n人工核对";
  await browserApi(page, "/api/knowledge", "POST", { key: "评价资料整理", value: note });
  await page.getByRole("button", { name: "刷新", exact: true }).click();
  const entries = page.getByRole("region", { name: "知识条目", exact: true });
  const row = entries.getByRole("article").filter({ has: page.getByRole("heading", { name: "原神 Genshin Impact 游戏评价 2025", exact: true }) });
  await expect(row.getByText("联网搜索", { exact: true })).toBeVisible();
  await expect(row.getByText("Web 搜索「原神 Genshin Impact 游戏评价 2025」返回 4 条结果。", { exact: true })).toBeVisible();
  await expect(row.locator("pre")).toBeHidden(); expect(await row.evaluate(element => element.getBoundingClientRect().height)).toBeLessThan(190);
  await row.getByText("查看内容", { exact: true }).click();
  const excerpt = row.getByRole("region", { name: "回答摘录", exact: true });
  await expect(excerpt.getByRole("heading", { name: "评价要点", exact: true })).toBeVisible();
  await expect(excerpt.locator("strong")).toHaveText("探索体验");
  await expect(excerpt.locator("img")).toHaveCount(0); expect(trackedImages).toEqual([]);
  await row.getByText("原始记录", { exact: true }).click(); await expect(row.locator("pre")).toHaveText(original);
  await chooseMenuAction(page, "联网搜索 · 原神 Genshin Impact 游戏评价 2025", "编辑 联网搜索 · 原神 Genshin Impact 游戏评价 2025");
  const editor = row.getByRole("textbox", { name: "修改这条记忆的内容", exact: true });
  await expect(editor).toHaveValue(original);
  const updated = original.replace("返回 4 条结果", "返回 5 条结果");
  await editor.fill(updated); await row.getByRole("button", { name: "保存", exact: true }).click();
  await expect(row.getByText("Web 搜索「原神 Genshin Impact 游戏评价 2025」返回 5 条结果。", { exact: true })).toBeVisible();
  expect((await browserData(page, "/api/knowledge")).find(entry => entry.id === added.body.data.id)).toMatchObject({ key: recordKey, value: updated });
  if (await row.getByText("收起内容", { exact: true }).isVisible()) await row.getByText("收起内容", { exact: true }).click();
  const manual = entries.getByRole("article").filter({ has: page.getByRole("heading", { name: "评价资料整理", exact: true }) });
  await manual.getByText("展开全文", { exact: true }).click(); await expect(manual.locator("details > p")).toHaveText(note); await expect(manual.locator("details > p")).toBeVisible();
  await manual.getByText("收起全文", { exact: true }).click();
  await entries.getByRole("textbox", { name: "搜索知识条目", exact: true }).fill("ce9cf191");
  await entries.getByRole("button", { name: "搜索", exact: true }).click(); await expect(entries.getByRole("article")).toHaveCount(1); await expect(row).toBeVisible();
  await entries.getByRole("textbox", { name: "搜索知识条目", exact: true }).fill(""); await entries.getByRole("button", { name: "搜索", exact: true }).click();
  await expect(entries.getByRole("article")).toHaveCount(3);
  await expect.poll(() => row.evaluate(element => element.getBoundingClientRect().height)).toBeLessThan(190);
  await mkdir(shots, { recursive: true }); await entries.screenshot({ path: join(shots, "entries-desktop-dark.png"), animations: "disabled" });
  await page.setViewportSize({ width: 390, height: 844 }); await page.emulateMedia({ reducedMotion: "reduce", colorScheme: "light" }); await page.evaluate(() => document.documentElement.classList.remove("dark"));
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await row.getByText("查看内容", { exact: true }).click(); await expect(excerpt.getByRole("heading", { name: "评价要点", exact: true })).toBeVisible();
  await row.getByText("收起内容", { exact: true }).click();
  await entries.screenshot({ path: join(shots, "entries-mobile-light.png"), animations: "disabled" });
  expect(errors).toEqual([]); expect(trackedImages).toEqual([]);
});
