  await page.getByRole("combobox", { name: "检索资料集合", exact: true }).click();
  await page.getByRole("option", { name: "产品政策", exact: true }).click();
  await mkdir(shots, { recursive: true }); await page.evaluate(() => { document.scrollingElement?.scrollTo(0, 0); document.querySelector(".workspace-content")?.scrollTo(0, 0); });
  await page.screenshot({ path: join(shots, "desktop-dark.png"), animations: "disabled" });
