  await page.unroute("**/api/knowledge");
  await sheet.getByRole("button", { name: "新增知识", exact: true }).click();
  await expect(sheet).toBeHidden();
  const row = page.getByRole("article").filter({ has: page.getByRole("heading", { name: "售后政策", exact: true }) });
  await expect(row).toBeVisible(); await expect(row.getByText(content, { exact: true })).toBeHidden();
  await row.getByText("展开全文", { exact: true }).click(); await expect(row.getByText(content, { exact: true })).toBeVisible();
